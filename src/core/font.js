export const FONT_W = 5;
export const FONT_H = 7;

export function textWidth(text, size = 1) {
  return text.length * 6 * size - size;
}

/** Draw text with its top-left (or centre/right) at x, y. Positions are rounded to whole pixels. */
export function drawText(ctx, text, x, y, color, size = 1, align = 'left', shadow = null) {
  const str = String(text).toUpperCase();
  const w = textWidth(str, size);
  let x0 = Math.round(align === 'center' ? x - w / 2 : align === 'right' ? x - w : x);
  const y0 = Math.round(y);
  const pass = (dx, dy, col) => {
    ctx.fillStyle = col;
    let cx = x0 + dx;
    for (const ch of str) {
      const rows = G[ch]?.split('/');
      if (rows) {
        for (let r = 0; r < FONT_H; r++) {
          for (let c = 0; c < FONT_W; c++) {
            if (rows[r][c] === '1') ctx.fillRect(cx + c * size, y0 + dy + r * size, size, size);
          }
        }
      }
      cx += 6 * size;
    }
  };
  if (shadow) pass(size, size, shadow);
  pass(0, 0, color);
}
